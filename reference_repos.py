"""
reference_repos.py

Writes REFERENCE_REPOS.md, the overview the Refinish Metal project reads to
know where to look things up: where DFHack's documentation is, what each repo
holds, and how to clone them.

The prose lives here and the figures come from the scans, so the figures can
never go stale. To change the wording, change this file and run the
generator again: an edit made to REFERENCE_REPOS.md itself is lost on the
next run. That happened once already: the mods_backup_premigration section
was added to the project's copy by hand, and the generator that wrote the
rest of the file was lost, so the copies in the repos fell behind it.
"""
from index_common import REPOS, HUB, repo_url, number_word


def and_list(xs):
    xs = list(xs)
    return xs[0] if len(xs) == 1 else ', '.join(xs[:-1]) + ' and ' + xs[-1]


def write(s):
    """s maps each repo name to its stats() dict; a repo without a clone is absent."""
    d, v, t = s['df_data_reference'], s['vanilla_raws_reference'], s['refinish_metal_tools']
    k, a = s['rm_knowledge_base'], s['argmod_injection_all_ports']
    h = k['dfhack_docs']
    m = s.get('mods_backup_premigration')
    L = []
    L.append("# Reference material\n")
    L.append(f"> Generated by `build_indexes.py`, in {HUB}'s `repo_index_generators/`. Edit the")
    L.append("> generator, not this file: the next run overwrites it.\n")
    L.append("Where to look things up for Refinish Metal. Everything lives in public GitHub repos")
    L.append("under `grungeisdead85` that are too large for the project mirror, DFHack's own")
    L.append(f"documentation included: it is in `{HUB}`, folder `dfhack_docs/`. Each repo's index,")
    L.append("and the DFHack manual's, is copied into this project's `indexes/` so it is readable")
    L.append("without cloning. `mods_backup_premigration` has no index: its section below")
    L.append("describes it.\n")
    L.append("---\n")

    # ---- DFHACK'S DOCUMENTATION ----
    # The four pages the project once kept, now read from the clone. Their
    # flat names stay in the table because older notes and code comments
    # cite them that way.
    L.append(f"## DFHack's documentation: in `{HUB}`, folder `dfhack_docs/`\n")
    L.append("DFHack's own manual, every page as plain text, as it ships in Dwarf Fortress's")
    L.append(f"`hack/docs/` folder: {h['pages']} pages, {h['changelogs']} changelogs and "
             f"{h['tools']} tool pages." + (f" The newest changelog entry is {h['version']}." if h['version'] else ''))
    L.append("`dfhack_docs_INDEX.md` lists every page and tool, outlines the pages below with")
    L.append("the line each section starts on, and shows where each DFHack name RM uses is")
    L.append("documented.\n")
    L.append("| Page in `dfhack_docs/` | Older notes call it | Read it for |")
    L.append("|---|---|---|")
    for rel, old, use in h['key_pages']:
        L.append(f"| `{rel}` | `{old}` | {use} |")
    L.append("")
    if h['repeat_util_not_in_lua_api']:
        L.append("`repeat-util` appears **nowhere** in `Lua API.txt`: check the modding guide for it.\n")
    if h['missing_key_pages']:
        L.append("**Not in the folder:** " + ', '.join(f"`{x}`" for x in h['missing_key_pages']) + ".\n")
    L.append("---\n")

    # ---- THE REPOS ----
    L.append("## The repos\n")
    L.append("## Standing instruction\n")
    L.append("**Do not answer from recall on any of the below. Read the source.**\n")
    L.append("| Question is about | Go to |")
    L.append("|---|---|")
    L.append(f"| DFHack API behaviour, `repeat-util`, `eventful`, overlays | `{HUB}`, `dfhack_docs/`: see `dfhack_docs_INDEX.md` |")
    L.append("| DF data structure layout, struct contents, enum values, `df.global` paths | `df_data_reference` |")
    L.append("| Vanilla token spellings, material and reaction IDs, graphics tags, ID collisions | `vanilla_raws_reference` |")
    L.append("| Whether something was attempted before | `refinish_metal_tools` |")
    L.append("| Whether something about DF, DFHack or RM is already established, and on what evidence; how an RM system was designed | `rm_knowledge_base` |")
    L.append("| The ArgMOD and Elemental Metals Library ports: what each injects, what stayed in raws and why | `argmod_injection_all_ports` |")
    L.append("| What a script did or said before the RM core migration | `mods_backup_premigration` |\n")
    L.append("If the answer is not in the project or the repos, say so rather than filling the")
    L.append("gap.\n")
    L.append("Clone once per session, on first need:\n")
    L.append("```bash")
    for r in REPOS:
        L.append(f"git clone --depth 1 {repo_url(r['name'])}.git")
    L.append("```\n")
    L.append("The sandbox resets between sessions, so this is not persistent. Sessions where")
    L.append("nothing calls for a lookup do not need a clone.\n")
    L.append("---\n")

    # ---- df_data_reference ----
    L.append(f"## `df_data_reference`: {d['size']}, {d['files']} files\n")
    L.append("Path maps and structure dumps captured from a **live game**. Flattened traces of")
    L.append("real objects, every field recursively expanded:\n")
    L.append("```")
    L.append('df.global.world.raws.reactions.reactions[116].code = "MAKE_QUICKLIME"')
    L.append("```\n")
    dirs = and_list(f"`{x}/`" for x in d['pm_dirs'])
    L.append(f"- {d['path_maps']} path maps across {dirs}")
    many = [f"{f} ({n})" for f, n in d['families'] if n > 1]
    single = sorted(f for f, n in d['families'] if n == 1)
    L.append("- Families covered: " + ', '.join(many) + (", plus " + ', '.join(single) if single else ''))
    L.append(f"- {d['dumps']} dumps, enums and notes: enum dumps (`item_type`, `furnace_type`,")
    L.append("  building types and skills), a struct field list for `item_corpsepiecest`, and")
    L.append("  assorted notes\n")
    L.append("**Go here when:** you need to know where a field actually lives, what a struct")
    L.append("really contains, or what an enum value maps to. This is ground truth over any")
    L.append("documentation, and over my recall.\n")
    L.append("---\n")

    # ---- vanilla_raws_reference ----
    L.append(f"## `vanilla_raws_reference`: {v['size']}, {v['files']} files\n")
    L.append("Complete unmodified vanilla DF raws plus vanilla sprite sheets, laid out mirroring")
    L.append("DF's own mod folders.\n")
    L.append(f"- {v['txt']} text raws: creatures, inorganics, reactions, items, entities, plants,")
    L.append("  descriptors, bodies, tissue and material templates, language, text sets")
    kinds = f"{v['png']} PNG" + (f", {v['bmp']} BMP" if v['bmp'] else '')
    L.append(f"- {v['images']} sprite sheets ({kinds}) across {v['image_dirs']} directories, plus tile pages")
    L.append(f"- {v['lua']} Lua files, in " + and_list(f"`{x}/`" for x in v['lua_dirs']) + "\n")
    L.append("**Go here when:** you need exact vanilla token spellings, existing material or")
    L.append("reaction IDs, graphics tags, or a check for ID collisions before injecting")
    L.append("something new.\n")
    L.append("Note: root `readme.txt` is Bay 12's public-domain waiver shipped with the raws,")
    L.append("not a repo description. The sprite images remain under copyright.\n")
    L.append("---\n")

    # ---- refinish_metal_tools ----
    L.append(f"## `refinish_metal_tools`: {t['size']}, {t['files']} files\n")
    L.append("Archived probe scripts from RM development. These are **periodic clear-outs of the")
    L.append(f"live scripts folder**, so the {number_word(t['dirs'])} directories are strata rather than categories.\n")
    L.append("**These tools are not to be resurrected or run, and they are hit and miss.** Many")
    L.append("are failures, half-finished, or superseded. A script existing here is not evidence")
    L.append("that its approach worked. They are kept for the paths they reference, the engine")
    L.append("questions they record, and functions worth harvesting into generalized RM tooling")
    L.append("later. Always read a file before trusting it, and verify anything load-bearing")
    L.append("against the live game.\n")
    L.append(f"- {t['lua']} Lua, {t['py']} Python, {t['unique']} unique by content")
    L.append(f"- {t['dfglobal']} of {t['files']} touch a `df.global` path")
    L.append("- Heaviest coverage: " + ', '.join(f"{n} ({c})" for n, c in t['topics']))
    L.append(f"- {t['caveat']} of {t['files']} files carry comments about something being broken, wrong, abandoned or")
    L.append("  superseded; those are flagged `!` in that repo's index")
    L.append("- Its index carries a topic index, a path index of every `df.global` path the")
    L.append("  archive *references*, and per-file purpose and function listings\n")
    L.append("**Go here when:** the question is \"did we already try this, and where?\" The path")
    L.append("index shows prior attempts, not proven answers. Use it to find the earlier work,")
    L.append("then read it critically.\n")
    if t['variants']:
        n = len(t['variants'])
        L.append(f"{number_word(n, capital=True)} {'tool exists' if n == 1 else 'tools exist'} "
                 "in two genuinely different versions, noted in that repo's index:")
        L.append(and_list(f"`{x}`" for x in t['variants']) + ".\n")
    L.append("---\n")

    # ---- rm_knowledge_base ----
    L.append(f"## `rm_knowledge_base`: {k['size']}, {k['files']} files\n")
    L.append("What RM's development has established about DF, DFHack and RM itself, RM's")
    L.append("development notes, and DFHack's own documentation. It also holds the index")
    L.append("generators (`repo_index_generators/`) and a copy of this overview.\n")
    L.append(f"- `rm_knowledge_base/`: {k['entries']} files in {number_word(len(k['areas']))} areas "
             f"({', '.join(k['areas'])}); every entry in them")
    L.append("  states one claim with its status (measured, code, decided or inference) and its")
    L.append("  evidence")
    L.append(f"- `RM_Notes/`: {k['notes']} development notes (design documents, schema references,")
    L.append("  measured mechanics, defect registers), kept here rather than in the project")
    L.append("  because of their size")
    L.append(f"- `dfhack_docs/`: DFHack's manual, {h['files']} files (see its section above),")
    L.append("  listed in the generated `dfhack_docs_INDEX.md`")
    L.append("- Its `INDEX.md` is written by hand; the generator checks it for files it does not")
    L.append("  list, leaving `dfhack_docs/` to its own index\n")
    L.append("**Go here when:** the question is whether something about DF, DFHack or RM has")
    L.append("already been established, and on what evidence, or how an RM system was designed")
    L.append("and why. Entries and notes record what was true when they were written; the live")
    L.append("code in the project is the source of truth.\n")
    L.append("---\n")

    # ---- argmod_injection_all_ports ----
    L.append(f"## `argmod_injection_all_ports`: {a['size']}, {a['files']} files\n")
    L.append("Other modders' mods ported to RM's module engine, each a complete DF mod folder:")
    L.append("its `data/` JSON is injected at runtime, its `objects/` and `graphics/` stay")
    L.append("ordinary raws. Its index lists each port's load order, what it injects, what its")
    L.append("raws still define, select or cut, and the port notes.\n")
    L.append("| Port | Prefix | Materials | Reactions | Categories |")
    L.append("|---|---|---|---|---|")
    for row in a['mods']:
        L.append(f"| {row['name']} | `{row['prefix'] or ''}` | {row['materials']} | "
                 f"{row['reactions']} | {row['categories']} |")
    L.append("")
    L.append("**Go here when:** a question touches one of these ports (what it injects, what")
    L.append("stayed in raws and why, bugs found in the source mods), or needs a worked example")
    L.append("of the module JSON at scale.\n")
    L.append("---\n")

    # ---- mods_backup_premigration ----
    head = f"{m['size']}, {m['files']} files" if m else "the premigration snapshot"
    L.append(f"## `mods_backup_premigration`: {head}\n")
    L.append(f"{repo_url('mods_backup_premigration')}\n")
    L.append("Refinish Metal, Making Fuel and Making Concrete exactly as they stood before the")
    L.append("RM core migration, made 2026-09-25: `refinish_steel/`, `making_fuel/` and")
    L.append("`making_concrete/`, each with its `scripts_modinstalled/` (RM also has")
    L.append("`scripts_modactive/`) and its data. When in doubt about what a script did or said")
    L.append("before the migration, look here: a lost comment or lesson, a removed function or")
    L.append("command (dye stock's `status()` is in")
    L.append("`making_fuel/scripts_modinstalled/making-fuel-dye-stock.lua`), the old form ids")
    L.append("and fields, or where code went. RM_Migration_Audit.md records the full")
    L.append("comparison. A snapshot, not a reference for how RM works now: the project's live")
    L.append("code is authoritative.\n")
    L.append("---\n")

    # ---- CAVEATS ----
    L.append("## Caveats that apply to every repo\n")
    L.append("- **Read-only.** I can clone and read. I cannot push. Changes still ship to you as")
    L.append("  FIND/REPLACE pairs.")
    L.append("- **Line endings are mixed and deliberate.** Nothing in these repos has been")
    L.append("  normalized by git. The tools archive in particular is mostly CRLF Lua, which")
    L.append("  cuts against RM's LF-for-Lua convention. Do not copy a file out of the archive")
    L.append("  into live RM without checking its endings.")
    L.append("- **These are reference, not source of truth for RM itself.** The live code in the")
    L.append("  project remains authoritative for how RM currently works. The archive records")
    L.append("  what was true when it was captured.")
    return '\n'.join(L)
